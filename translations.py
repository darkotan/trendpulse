# Language detection mapping: Accept-Language prefix -> code
LANG_MAP = {
    'zh': 'zh', 'cmn': 'zh', 'yue': 'zh',
    'ja': 'ja', 'jp': 'ja',
    'ko': 'ko', 'kr': 'ko',
    'fr': 'fr',
    'de': 'de',
    'es': 'es',
    'pt': 'pt', 'br': 'pt',
    'ar': 'ar',
    'ru': 'ru',
}

def detect_language(accept_lang: str = '') -> str:
    """Detect language from Accept-Language header. Returns a supported language code."""
    if not accept_lang:
        return 'en'
    al = accept_lang.lower().strip()
    # Check each known language prefix
    for prefix, code in LANG_MAP.items():
        if prefix in al.split(',')[0] or f'{prefix}-' in al or f',{prefix}' in al:
            return code
    return 'en'

def get_translations(lang: str) -> dict:
    """Get translation dict for given language, fallback to English."""
    return TRANSLATIONS.get(lang, TRANSLATIONS['en'])
